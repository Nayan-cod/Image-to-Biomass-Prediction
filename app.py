# ----------------- Load Models -----------------
@st.cache_resource
def load_pipeline_models():
    base_dir = "."
    info_path = os.path.join(base_dir, "best_model_info.pkl")
    regressor_path = os.path.join(base_dir, "best_regressor.joblib")
    
    if not os.path.exists(info_path) or not os.path.exists(regressor_path):
        st.error("Error: Trained model files not found! Please run the training pipeline first.")
        return None, None
        
    model_info = joblib.load(info_path)
    regressor = joblib.load(regressor_path)
    return regressor, model_info

@st.cache_resource
def load_deep_models():
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    
    # 1. SegFormer
    seg_processor = SegformerImageProcessor.from_pretrained("nvidia/segformer-b0-finetuned-ade-512-512")
    seg_model = SegformerForSemanticSegmentation.from_pretrained("nvidia/segformer-b0-finetuned-ade-512-512").to(device)
    seg_model.eval()
    
    # 2. Depth Anything
    depth_processor = AutoImageProcessor.from_pretrained("LiheYoung/depth-anything-small-hf")
    depth_model = AutoModelForDepthEstimation.from_pretrained("LiheYoung/depth-anything-small-hf").to(device)
    depth_model.eval()
    
    # 3. DINOv2
    dino_processor = AutoImageProcessor.from_pretrained("facebook/dinov2-small")
    dinov2_model = AutoModel.from_pretrained("facebook/dinov2-small", output_attentions=True).to(device)
    dinov2_model.eval()
    
    return device, seg_processor, seg_model, depth_processor, depth_model, dino_processor, dinov2_model

def overlay_heatmap(img_rgb, heatmap, alpha=0.5):
    # Resize heatmap to match image
    heatmap_resized = cv2.resize(heatmap, (img_rgb.shape[1], img_rgb.shape[0]))
    # Normalize to 0-255
    heatmap_norm = (heatmap_resized - heatmap_resized.min()) / (heatmap_resized.max() - heatmap_resized.min() + 1e-8)
    heatmap_color = cv2.applyColorMap(np.uint8(255 * heatmap_norm), cv2.COLORMAP_JET)
    heatmap_color = cv2.cvtColor(heatmap_color, cv2.COLOR_BGR2RGB)
    overlayed_img = cv2.addWeighted(img_rgb, 1 - alpha, heatmap_color, alpha, 0)
    return overlayed_img

