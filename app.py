# ----------------- Main App Logic -----------------
uploaded_file = st.file_uploader("📸 Upload an RGB Pasture Image (JPG/JPEG/PNG format)", type=["jpg", "jpeg", "png"])

if uploaded_file is not None and regressor is not None:
    # 1. Read and display original image
    image = Image.open(uploaded_file)
    img_rgb = np.array(image)
    
    col1, col2 = st.columns(2)
    with col1:
        st.image(img_rgb, caption="Uploaded Pasture Image", width="stretch")
        
    # Run processing
    with st.spinner("Running GPU foundation models and predicting biomass..."):
        # 1. SegFormer Segmentation
        inputs_seg = seg_processor(images=img_rgb, return_tensors="pt").to(device)
        with torch.no_grad():
            outputs_seg = seg_model(**inputs_seg)
            logits_seg = outputs_seg.logits
            upsampled_logits = nn.functional.interpolate(
                logits_seg,
                size=img_rgb.shape[:2],
                mode="bilinear",
                align_corners=False
            )
            pred_mask = upsampled_logits.argmax(dim=1)[0].cpu().numpy()
            
        # Map classes (updated for pasture-specific ADE20K predictions)
        # Vegetation: tree (4), grass (9), plant (17), field (29), mountain (16)
        veg_mask = np.isin(pred_mask, [4, 9, 17, 29, 16])
        # Soil/Dead: everything else (e.g. wall, earth, path, etc.)
        soil_mask = ~veg_mask
        
        total_pixels = pred_mask.size
        veg_coverage = np.sum(veg_mask) / total_pixels
        soil_coverage = np.sum(soil_mask) / total_pixels
        
        green_ratio = veg_coverage / (veg_coverage + soil_coverage + 1e-6)
        dead_ratio = soil_coverage / (veg_coverage + soil_coverage + 1e-6)
        
        # Color code: Green Veg (green), Dead/Soil (yellow)
        seg_color = np.zeros_like(img_rgb)
        seg_color[veg_mask] = [46, 139, 87] # SeaGreen
        seg_color[soil_mask] = [218, 165, 32] # GoldenRod
        
        with col2:
            st.image(seg_color, caption="SegFormer Pasture Segmentation Mask (Green: Green Veg, Yellow: Soil/Dead)", width="stretch")
            
        # 2. Depth Anything Monocular Depth
        inputs_depth = depth_processor(images=img_rgb, return_tensors="pt").to(device)
        with torch.no_grad():
            outputs_depth = depth_model(**inputs_depth)
            depth = outputs_depth.predicted_depth
            depth = nn.functional.interpolate(
                depth.unsqueeze(1),
                size=img_rgb.shape[:2],
                mode="bilinear",
                align_corners=False
            ).squeeze(1)[0].cpu().numpy()
            
        depth_mean = np.mean(depth)
        depth_std = np.std(depth)
        depth_var = np.var(depth)
        
        # 3. DINOv2 Feature Extraction and Self-Attention
        inputs_dino = dino_processor(images=img_rgb, return_tensors="pt").to(device)
        with torch.no_grad():
            outputs_dino = dinov2_model(**inputs_dino)
            
        dino_feats = outputs_dino.last_hidden_state[0, 0].cpu().numpy()
        
        # 4. Assemble Features & Predict
        feats_dict = {
            'veg_coverage': veg_coverage,
            'green_ratio': green_ratio,
            'dead_ratio': dead_ratio,
            'depth_mean': depth_mean,
            'depth_std': depth_std,
            'depth_var': depth_var,
            'Height_Ave_cm': height_input,
            'Pre_GSHH_NDVI': ndvi_input
        }
        for f_idx, val in enumerate(dino_feats):
            feats_dict[f'dino_{f_idx}'] = val
            
        features_ordered = [feats_dict[name] for name in model_info['features']]
        features_array = np.array(features_ordered).reshape(1, -1)
        
        # Predict using RF
        predictions_raw = regressor.predict(features_array)[0]
        
        # Safeguard predictions to positive
        predictions_raw = np.clip(predictions_raw, 0, None)
        predictions_kgha = predictions_raw * GRAMS_TO_KG_HA
        
        # 5. Display Predictions
        st.markdown("### 📊 Predicted Pasture Biomass (kg/ha)")
        
        m_col1, m_col2, m_col3, m_col4, m_col5 = st.columns(5)
        
        def render_metric_card(col, label, val):
            col.markdown(f"""
                <div class="metric-card">
                    <div class="metric-label">{label}</div>
                    <div class="metric-value">{val:.1f} <span style="font-size: 1rem;">kg/ha</span></div>
                </div>
            """, unsafe_allow_html=True)
            
        render_metric_card(m_col1, "Dry Green Vegetation (ex clover)", predictions_kgha[0])
        render_metric_card(m_col2, "Dry Dead Material", predictions_kgha[1])
        render_metric_card(m_col3, "Dry Clover Biomass", predictions_kgha[2])
        render_metric_card(m_col4, "Green Dry Matter (GDM)", predictions_kgha[3])
        render_metric_card(m_col5, "Total Dry Biomass", predictions_kgha[4])
        
        # 6. DINOv2 Self-Attention Map Overlay
        st.markdown("### 🔍 DINOv2 Self-Attention Explainability (Biomass Attention Driver)")
        
        attentions = outputs_dino.attentions[-1]
        nh = attentions.shape[1]
        th_attn = attentions[0, :, 0, 1:].reshape(nh, 16, 16)
        mean_attn = torch.mean(th_attn, dim=0).cpu().numpy()
        
        overlay = overlay_heatmap(img_rgb, mean_attn, alpha=0.5)
        
        gc_col1, gc_col2 = st.columns(2)
        with gc_col1:
            st.image(img_rgb, caption="Original Pasture Image", width="stretch")
        with gc_col2:
            st.image(overlay, caption="DINOv2 Self-Attention Overlay (Red indicates regions driving model predictions)", width="stretch")
else:
    st.info("👈 Please upload an RGB pasture image to start the prediction pipeline.")
